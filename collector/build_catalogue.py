"""Build data/catalogue/cards.csv from official Bandai card data (EN + JP).

Source: the punk-records dataset (github.com/buhbbl/punk-records), generated by vegapull from the
official card lists at en.onepiece-cardgame.com and www.onepiece-cardgame.com.

  git clone --depth 1 https://github.com/buhbbl/punk-records /tmp/punk-records
  python collector/build_catalogue.py /tmp/punk-records

One row per printing (base card, each parallel/alt art, SP, reprint), with the set it was actually
released in, its rarity, and whether it exists in English, Japanese or both.
"""
import csv, glob, json, os, re, sys, collections

SRC = sys.argv[1]
ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.join(ROOT, "data", "catalogue", "cards.csv")

RARITY = {"Common": "C", "Uncommon": "UC", "Rare": "R", "SuperRare": "SR", "SecretRare": "SEC", "Leader": "L",
          "Special": "SP", "TreasureRare": "TR", "Promo": "P"}
SUFFIX_SET = {"204": "EB-04", "801": "Other", "901": "Promo"}   # pack-id suffixes with no clean label


def pack_labels():
    packs = json.load(open(os.path.join(SRC, "english", "packs.json"), encoding="utf-8"))
    out = {}
    for pid, p in packs.items():
        label = (p.get("title_parts") or {}).get("label")
        suf = pid[-3:]
        if suf in SUFFIX_SET:
            out[suf] = SUFFIX_SET[suf]
        elif label:
            out[suf] = {"OP14-EB04": "OP-14", "OP15-EB04": "OP-15"}.get(label, label)
    out.setdefault("204", "EB-04")
    return out


def load(lang):
    cards = {}
    for f in glob.glob(os.path.join(SRC, lang, "cards", "*", "*.json")):
        c = json.load(open(f, encoding="utf-8"))
        cards[c["id"]] = c
    return cards


def main():
    labels = pack_labels()
    en, jp = load("english"), load("japanese")
    rows = []
    for pid in sorted(set(en) | set(jp)):
        c = en.get(pid) or jp[pid]
        code = re.sub(r"_[a-z]\d+$", "", pid)
        m = re.search(r"_([a-z])(\d+)$", pid)
        rarity = RARITY.get(c.get("rarity"), c.get("rarity") or "?")
        if rarity == "SP":
            variant = "SP"
        elif rarity == "TR":
            variant = "Treasure"
        elif not m:
            variant = "Base"
        elif m.group(1) == "p":
            variant = f"Parallel {m.group(2)}"
        else:
            variant = f"Reprint {m.group(2)}"
        suf = str(c.get("pack_id", ""))[-3:]
        set_code = labels.get(suf, "Other")
        if code.startswith("EB04") and set_code in ("OP-14", "OP-15"):
            set_code = "EB-04"                     # EN prints EB-04 inside the OP14/OP15 products
        rows.append({
            "printing_id": pid, "card_code": code, "name": (en.get(pid) or {}).get("name") or c["name"],
            "name_jp": (jp.get(pid) or {}).get("name", ""), "rarity": rarity, "variant": variant,
            "card_type": c.get("category", ""), "color": "/".join(c.get("colors") or []),
            "traits": "/".join(c.get("types") or []), "set_code": set_code,
            "en": int(pid in en), "jp": int(pid in jp),
        })
    en_name = {}
    for pid, c in en.items():
        en_name.setdefault(re.sub(r"_[a-z]\d+$", "", pid), c["name"])
    for r in rows:
        r["name"] = en_name.get(r["card_code"], r["name"])
    # base rarity for codes whose base printing is only known through a parallel
    base_r = {r["card_code"]: r["rarity"] for r in rows if r["variant"] == "Base"}
    for r in rows:
        if r["rarity"] in ("SP", "TR", "?") and r["variant"] != "Base":
            continue
        if r["rarity"] == "?" and r["card_code"] in base_r:
            r["rarity"] = base_r[r["card_code"]]
    with open(OUT, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader(); w.writerows(rows)
    print(f"{len(rows)} printings, {len({r['card_code'] for r in rows})} card codes")
    print("EN only", sum(r['en'] and not r['jp'] for r in rows), "JP only", sum(r['jp'] and not r['en'] for r in rows))
    print(collections.Counter(r["rarity"] for r in rows))
    print(sorted(collections.Counter(r["set_code"] for r in rows).items()))


if __name__ == "__main__":
    main()
